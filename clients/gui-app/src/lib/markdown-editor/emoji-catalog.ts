/**
 * Entries whose name or keywords contain every word of `query`, in catalog
 * order. An empty query matches nothing; callers show the groups instead.
 */
export function searchEmoji(query: string): readonly EmojiEntry[] {
  const words = query
    .toLowerCase()
    .split(/\s+/)
    .filter((word) => word !== "");
  if (words.length === 0) return [];
  const results: EmojiEntry[] = [];
  for (const group of EMOJI_GROUPS) {
    for (const candidate of group.entries) {
      const haystack = [candidate.name, ...candidate.keywords];
      if (words.every((word) => haystack.some((text) => text.includes(word)))) {
        results.push(candidate);
      }
    }
  }
  return results;
}
